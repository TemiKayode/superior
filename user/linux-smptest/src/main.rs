//! A Linux program, for the Linux personality's test (it is not one of
//! Superior's): Linux's system calls made directly, no C library.
//!
//! It checks `sched_getaffinity` gives it at least two CPUs, then starts a
//! second thread (`clone`, `CLONE_THREAD`) and the two hand a word back
//! and forth, 2000 times each way, spinning on it without a system call.
//! On one CPU every hand-over waits for the spinning thread's time slice
//! to run out (20 ms here), so that takes at least 80 seconds; with the
//! threads on two CPUs at once, a moment. Before handing the word over
//! the first time, while the second thread spins on the other CPU, it
//! registers for and makes `membarrier`'s private expedited barrier, and
//! a global one, each of which must return 0. If the hand-overs are done
//! within 10 seconds (`clock_gettime`), it says so and exits 0; else it
//! exits 1.
//!
//! All code addresses it takes are relative to the program counter, so as
//! a static PIE it has nothing to relocate.

#![no_std]
#![no_main]

// The word goes from 0 to 4000: the first thread makes it odd, the
// second even.
#[cfg(target_arch = "x86_64")]
core::arch::global_asm!(
    ".globl _start",
    "_start:",
    "sub rsp, 16",
    // sched_getaffinity(0, 8, mask): CPU 1 there too?
    "xor edi, edi",
    "mov esi, 8",
    "mov rdx, rsp",
    "mov eax, 204",
    "syscall",
    "cmp rax, 8",
    "jne smp_fail",
    "test qword ptr [rsp], 2",
    "jz smp_fail",
    // clock_gettime(CLOCK_MONOTONIC): the seconds in r12.
    "mov edi, 1",
    "mov rsi, rsp",
    "mov eax, 228",
    "syscall",
    "mov r12, [rsp]",
    // clone(CLONE_VM | FS | FILES | SIGHAND | THREAD | SYSVSEM, stack)
    "mov edi, 0x50f00",
    "lea rsi, [rip + smp_stack_top]",
    "xor edx, edx",
    "xor r10d, r10d",
    "xor r8d, r8d",
    "mov eax, 56",
    "syscall",
    "test rax, rax",
    "js smp_fail",
    "jz smp_child",
    // membarrier: register (16), private expedited (8), global (1).
    "mov edi, 16",
    "xor esi, esi",
    "xor edx, edx",
    "mov eax, 324",
    "syscall",
    "test rax, rax",
    "jnz smp_fail",
    "mov edi, 8",
    "xor esi, esi",
    "xor edx, edx",
    "mov eax, 324",
    "syscall",
    "test rax, rax",
    "jnz smp_fail",
    "mov edi, 1",
    "xor esi, esi",
    "xor edx, edx",
    "mov eax, 324",
    "syscall",
    "test rax, rax",
    "jnz smp_fail",
    "2:",
    "mov rax, [rip + smp_turn]",
    "test al, 1",
    "jz 3f",
    "pause",
    "jmp 2b",
    "3:",
    "cmp rax, 4000",
    "je 4f",
    "inc rax",
    "mov [rip + smp_turn], rax",
    "jmp 2b",
    "4:",
    "mov edi, 1",
    "mov rsi, rsp",
    "mov eax, 228",
    "syscall",
    "mov rax, [rsp]",
    "sub rax, r12",
    "cmp rax, 10",
    "ja smp_fail",
    "mov edi, 1",
    "lea rsi, [rip + smp_msg]",
    "mov edx, 24",
    "mov eax, 1",
    "syscall",
    "xor edi, edi",
    "jmp smp_exit",
    "smp_fail:",
    "mov edi, 1",
    "smp_exit:",
    "mov eax, 231",
    "syscall",
    // The second thread: makes the word even, until 4000; then exit.
    "smp_child:",
    "mov rax, [rip + smp_turn]",
    "test al, 1",
    "jnz 5f",
    "pause",
    "jmp smp_child",
    "5:",
    "inc rax",
    "mov [rip + smp_turn], rax",
    "cmp rax, 4000",
    "jne smp_child",
    "xor edi, edi",
    "mov eax, 60",
    "syscall",
    ".section .rodata",
    "smp_msg: .ascii \"two threads ran at once\\n\"",
    ".section .bss",
    ".balign 16",
    "smp_turn: .quad 0",
    ".balign 16",
    ".space 4096",
    "smp_stack_top:",
);

#[cfg(target_arch = "aarch64")]
core::arch::global_asm!(
    ".globl _start",
    "_start:",
    "sub sp, sp, #32",
    // sched_getaffinity(0, 8, mask): CPU 1 there too?
    "mov x0, #0",
    "mov x1, #8",
    "mov x2, sp",
    "mov x8, #123",
    "svc #0",
    "cmp x0, #8",
    "b.ne smp_fail",
    "ldr x0, [sp]",
    "tst x0, #2",
    "b.eq smp_fail",
    // clock_gettime(CLOCK_MONOTONIC): the seconds in x19.
    "mov x0, #1",
    "mov x1, sp",
    "mov x8, #113",
    "svc #0",
    "ldr x19, [sp]",
    // clone(CLONE_VM | FS | FILES | SIGHAND | THREAD | SYSVSEM, stack)
    "movz x0, #0x0f00",
    "movk x0, #0x5, lsl #16",
    "adrp x1, smp_stack_top",
    "add x1, x1, :lo12:smp_stack_top",
    "mov x2, #0",
    "mov x3, #0",
    "mov x4, #0",
    "mov x8, #220",
    "svc #0",
    "cmp x0, #0",
    "b.lt smp_fail",
    "b.eq smp_child",
    // membarrier: register (16), private expedited (8), global (1).
    "mov x0, #16",
    "mov x1, #0",
    "mov x2, #0",
    "mov x8, #283",
    "svc #0",
    "cbnz x0, smp_fail",
    "mov x0, #8",
    "mov x1, #0",
    "mov x2, #0",
    "mov x8, #283",
    "svc #0",
    "cbnz x0, smp_fail",
    "mov x0, #1",
    "mov x1, #0",
    "mov x2, #0",
    "mov x8, #283",
    "svc #0",
    "cbnz x0, smp_fail",
    "adrp x9, smp_turn",
    "add x9, x9, :lo12:smp_turn",
    "mov x10, #4000",
    "2:",
    "ldar x0, [x9]",
    "tbz x0, #0, 3f",
    "yield",
    "b 2b",
    "3:",
    "cmp x0, x10",
    "b.eq 4f",
    "add x0, x0, #1",
    "stlr x0, [x9]",
    "b 2b",
    "4:",
    "mov x0, #1",
    "mov x1, sp",
    "mov x8, #113",
    "svc #0",
    "ldr x0, [sp]",
    "sub x0, x0, x19",
    "cmp x0, #10",
    "b.hi smp_fail",
    "mov x0, #1",
    "adrp x1, smp_msg",
    "add x1, x1, :lo12:smp_msg",
    "mov x2, #24",
    "mov x8, #64",
    "svc #0",
    "mov x0, #0",
    "b smp_exit",
    "smp_fail:",
    "mov x0, #1",
    "smp_exit:",
    "mov x8, #94",
    "svc #0",
    // The second thread: makes the word even, until 4000; then exit.
    "smp_child:",
    "adrp x9, smp_turn",
    "add x9, x9, :lo12:smp_turn",
    "mov x10, #4000",
    "6:",
    "ldar x0, [x9]",
    "tbnz x0, #0, 5f",
    "yield",
    "b 6b",
    "5:",
    "add x0, x0, #1",
    "stlr x0, [x9]",
    "cmp x0, x10",
    "b.ne 6b",
    "mov x0, #0",
    "mov x8, #93",
    "svc #0",
    ".section .rodata",
    "smp_msg: .ascii \"two threads ran at once\\n\"",
    ".section .bss",
    ".balign 16",
    "smp_turn: .quad 0",
    ".balign 16",
    ".space 4096",
    "smp_stack_top:",
);

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    loop {}
}
