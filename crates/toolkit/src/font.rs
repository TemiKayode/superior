/// Character `c`'s glyph.
pub fn glyph(c: u8) -> &'static [u8; 7] {
    let c = if (32..=126).contains(&c) { c } else { b'?' };
    &GLYPHS[(c - 32) as usize]
}

/// Whether font pixel (`col`, `row`) of character `c` is set.
pub fn lit(c: u8, col: u32, row: u32) -> bool {
    col < WIDTH && row < HEIGHT && glyph(c)[row as usize] >> (WIDTH - 1 - col) & 1 == 1
}

/// How wide `text` is drawn at `scale`, in screen pixels (no space after
/// the last glyph).
pub fn width(text: &[u8], scale: u32) -> u32 {
    (text.len() as u32 * ADVANCE).saturating_sub(1) * scale
}

/// Whether (`dx`, `dy`) from the top left of `text` drawn at `scale` is a
/// pixel of a glyph.
pub fn text_lit(text: &[u8], scale: u32, dx: u32, dy: u32) -> bool {
    let (cx, cy) = (dx / scale, dy / scale);
    let i = (cx / ADVANCE) as usize;
    i < text.len() && lit(text[i], cx % ADVANCE, cy)
}
