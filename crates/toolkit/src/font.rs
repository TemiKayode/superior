//! column. Other characters are drawn as `?`.
//!
//! Text is UTF-8: [`width`] and [`text_lit`] take it a character at a
//! time (a code point past Latin-1, or bytes that are not UTF-8, one `?`),
//! and [`count`], [`ahead`] and [`back`] measure and step through it by
//! characters, for the toolkit's cursors.

