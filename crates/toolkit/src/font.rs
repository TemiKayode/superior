/// Latin-1 character `c`'s glyph.
pub fn glyph(c: u8) -> &'static [u8; 7] {
    match c {
        32..=126 => &GLYPHS[(c - 32) as usize],
        0xa0.. => &LATIN[(c - 0xa0) as usize],
        _ => &GLYPHS[(b'?' - 32) as usize],
    }
}

/// Whether byte `b` begins a character of UTF-8 text (is not a
/// continuation byte).
pub fn begins(b: u8) -> bool {
    b & 0xc0 != 0x80
}

/// How many characters UTF-8 text `text` holds.
pub fn count(text: &[u8]) -> usize {
    text.iter().filter(|&&b| begins(b)).count()
}

/// The place `n` characters after byte `at` of `text` (its end at most).
pub fn ahead(text: &[u8], at: usize, n: usize) -> usize {
    let mut i = at.min(text.len());
    for _ in 0..n {
        if i == text.len() {
            break;
        }
        i += 1;
        while i < text.len() && !begins(text[i]) {
            i += 1;
        }
    }
    i
}

/// The place `n` characters before byte `at` of `text` (its start at
/// most).
pub fn back(text: &[u8], at: usize, n: usize) -> usize {
    let mut i = at.min(text.len());
    for _ in 0..n {
        if i == 0 {
            break;
        }
        i -= 1;
        while i > 0 && !begins(text[i]) {
            i -= 1;
        }
    }
    i
}

/// Latin-1 character `c` as UTF-8: its bytes and how many.
pub fn encode(c: u8) -> ([u8; 2], usize) {
    if c < 0x80 { ([c, 0], 1) } else { ([0xc0 | c >> 6, 0x80 | (c & 0x3f)], 2) }
}

/// The Latin-1 character UTF-8 text `text` begins with (`?` past Latin-1
/// or if it is not UTF-8), if it holds one.
pub fn first(text: &[u8]) -> Option<u8> {
    let (&b, rest) = text.split_first()?;
    Some(match (b, rest.first()) {
        (0..0x80, _) => b,
        (0xc2 | 0xc3, Some(&c)) if !begins(c) => (b & 0x1f) << 6 | (c & 0x3f),
        _ => b'?',
    })
}

/// Whether font pixel (`col`, `row`) of character `c` is set.
pub fn lit(c: u8, col: u32, row: u32) -> bool {
    col < WIDTH && row < HEIGHT && glyph(c)[row as usize] >> (WIDTH - 1 - col) & 1 == 1
}

/// How wide UTF-8 text `text` is drawn at `scale`, in screen pixels (no
/// space after the last glyph).
pub fn width(text: &[u8], scale: u32) -> u32 {
    (count(text) as u32 * ADVANCE).saturating_sub(1) * scale
}

/// Whether (`dx`, `dy`) from the top left of UTF-8 text `text` drawn at
/// `scale` is a pixel of a glyph.
pub fn text_lit(text: &[u8], scale: u32, dx: u32, dy: u32) -> bool {
    let (cx, cy) = (dx / scale, dy / scale);
    let at = ahead(text, 0, (cx / ADVANCE) as usize);
    first(&text[at..]).is_some_and(|c| lit(c, cx % ADVANCE, cy))
}
